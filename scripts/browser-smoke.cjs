const fs = require('node:fs');
const path = require('node:path');
const root = path.resolve(__dirname, '..');
const { assertModelPermission } = require('./model-guard.cjs');
const { chromium, expect } = require(path.join(root, 'frontend/node_modules/@playwright/test'));
const env = Object.fromEntries(fs.readFileSync(path.join(root, '.env'), 'utf8').split(/\r?\n/).filter(x => x && !x.startsWith('#')).map(line => { const i = line.indexOf('='); return [line.slice(0, i), line.slice(i + 1)]; }));
const output = path.join(root, '.runtime', 'screenshots');
fs.mkdirSync(output, { recursive: true });

(async () => {
  const browser = await chromium.launch({ channel: 'msedge', headless: true });
  const context = await browser.newContext({ viewport: { width: 1440, height: 1000 } });
  const page = await context.newPage();
  const errors = [];
  page.on('pageerror', error => errors.push(error.message));
  const checks = [];
  const login = async (username, password) => {
    await page.goto('http://127.0.0.1:5180');
    await page.getByLabel('用户名', { exact: true }).fill(username);
    await page.getByLabel('密码', { exact: true }).fill(password);
    await page.getByRole('button', { name: '登录工作台' }).click();
    await expect(page.getByRole('navigation', { name: '主导航' })).toBeVisible();
  };
  const nav = name => page.getByRole('navigation', { name: '主导航' }).getByRole('button', { name, exact: true }).click();
  try {
    await page.goto('http://127.0.0.1:5180');
    await page.screenshot({ path: path.join(output, 'login.png'), fullPage: true });
    await login('admin', env.ADMIN_PASSWORD);
    const initialStatus = await page.evaluate(async () => {
      const response = await fetch('/api/system/status', { headers: { Authorization: 'Bearer ' + sessionStorage.getItem('helpdesk-token') } });
      if (!response.ok) throw new Error('Cannot verify model configuration before browser smoke');
      const envelope = await response.json();
      if (envelope.code !== 200 || envelope.data?.ai?.status !== 'ok') throw new Error('AI status is not ready; refusing potentially paid writes');
      return envelope.data.ai;
    });
    assertModelPermission(initialStatus, process.argv.includes('--allow-model'));
    await expect(page.getByText('当前账户授权范围').first()).toBeVisible();
    await page.screenshot({ path: path.join(output, 'dashboard.png'), fullPage: true });
    checks.push('real admin login and dashboard');
    for (const name of ['企业知识库', '工单协作', '系统状态', '用户管理']) {
      await nav(name);
      await expect(page.locator('main h1')).toContainText(name);
      await expect(page.getByRole('alert')).toHaveCount(0);
    }
    checks.push('all admin pages load without visible API errors');
    await nav('企业知识库');
    const title = '浏览器上传验收-' + Date.now();
    await page.getByRole('button', { name: '上传文档', exact: true }).click();
    await page.getByLabel('文档标题', { exact: true }).fill(title);
    await page.getByLabel('选择文档文件').setInputFiles({ name: 'browser-smoke.md', mimeType: 'text/markdown', buffer: Buffer.from('# 浏览器验收\n上传、解析和索引应完整执行。', 'utf8') });
    const dialog = page.getByRole('dialog');
    await dialog.locator('button[type="submit"], button:not([type])').filter({ hasText: /上传|保存/ }).last().click();
    await expect(page.getByRole('dialog')).toHaveCount(0);
    const row = page.locator('tr').filter({ hasText: title });
    await expect(row).toContainText('已就绪', { timeout: 90000 });
    await page.screenshot({ path: path.join(output, 'documents.png'), fullPage: true });
    await page.getByRole('button', { name: '删除 ' + title, exact: true }).click();
    await page.getByRole('button', { name: '确认删除', exact: true }).click();
    await expect(row).toHaveCount(0);
    checks.push('browser upload -> asynchronous READY -> delete');
    await page.getByRole('button', { name: '退出登录' }).click();
    await login('employee', env.EMPLOYEE_PASSWORD);
    await expect(page.getByRole('button', { name: '用户管理', exact: true })).toHaveCount(0);
    await nav('企业知识库');
    await expect(page.getByRole('button', { name: '上传文档', exact: true })).toHaveCount(0);
    await expect(page.locator('main')).not.toContainText('HR请假与考勤');
    checks.push('employee UI permissions and department document scope');
    await nav('知识助手');
    await expect(page.getByLabel('输入问题')).toBeVisible();
    await page.getByLabel('输入问题').fill('VPN E809 连接失败怎么办？');
    await page.getByRole('button', { name: '发送问题', exact: true }).click();
    await expect(page.locator('.source-card').first()).toBeVisible({ timeout: 90000 });
    await page.locator('.source-card').first().click();
    await expect(page.getByRole('dialog', { name: '知识来源' })).toBeVisible();
    await page.getByRole('button', { name: '关闭弹窗' }).click();
    await page.getByLabel('同时生成工单草稿').check();
    const ticketTitle = 'VPN E809 仍未解决，浏览器验收申请 IT 协助 ' + Date.now();
    await page.getByLabel('输入问题').fill(ticketTitle);
    await page.getByRole('button', { name: '发送问题', exact: true }).click();
    await expect(page.getByRole('button', { name: '确认创建工单' })).toBeVisible({ timeout: 90000 });
    await page.getByRole('button', { name: '确认创建工单' }).scrollIntoViewIfNeeded();
    await page.screenshot({ path: path.join(output, 'assistant.png'), fullPage: true, animations: 'disabled' });
    await page.getByRole('button', { name: '确认创建工单' }).click();
    await expect(page.locator('.success-box')).toContainText('已创建', { timeout: 30000 });
    checks.push('real UI retrieval, citation dialog, ticket draft and approval');
    await page.getByRole('button', { name: '查看工单', exact: true }).click();
    await expect(page.locator('main')).toContainText('浏览器验收申请 IT 协助');
    await page.screenshot({ path: path.join(output, 'ticket.png'), fullPage: true });
    await page.getByRole('button', { name: '退出登录' }).click();
    await login('agent', env.AGENT_PASSWORD);
    await nav('工单协作');
    await page.getByLabel('搜索工单').fill(ticketTitle);
    await page.locator('.table-title').filter({ hasText: ticketTitle }).click();
    await page.getByRole('button', { name: '开始处理', exact: true }).click();
    await page.getByRole('button', { name: '标记已解决', exact: true }).click();
    await page.getByLabel('解决方案', { exact: true }).fill('已核对网关配置，浏览器全流程验收完成。');
    await page.getByRole('button', { name: '确认提交', exact: true }).click();
    await expect(page.getByRole('dialog')).toHaveCount(0);
    await page.getByRole('button', { name: '退出登录' }).click();
    await login('employee', env.EMPLOYEE_PASSWORD);
    await nav('工单协作');
    await page.getByLabel('搜索工单').fill(ticketTitle);
    await page.locator('.table-title').filter({ hasText: ticketTitle }).click();
    await page.getByRole('button', { name: '评价并关闭工单', exact: true }).click();
    await page.getByRole('dialog', { name: '评价并关闭工单' }).getByRole('combobox').selectOption('5');
    await page.getByRole('button', { name: '确认提交', exact: true }).click();
    await expect(page.locator('.page-title .badge')).toHaveText('已关闭');
    await page.screenshot({ path: path.join(output, 'ticket-closed.png'), fullPage: true });
    checks.push('browser staff processing and employee rating/closure');
    await page.setViewportSize({ width: 390, height: 844 });
    await page.getByRole('button', { name: '打开导航' }).click();
    await nav('工作概览');
    await expect(page.locator('.sidebar')).not.toHaveClass(/is-open/);
    await expect(page.locator('.stat-card strong').first()).not.toHaveText('…');
    await page.screenshot({ path: path.join(output, 'mobile.png'), fullPage: true, animations: 'disabled' });
    const overflow = await page.evaluate(() => document.documentElement.scrollWidth > window.innerWidth + 1);
    expect(overflow).toBe(false);
    checks.push('390px mobile navigation and no horizontal page overflow');
    expect(errors).toEqual([]);
    fs.writeFileSync(path.join(root, 'docs', 'browser-result.json'), JSON.stringify({ passed: checks, pageErrors: errors, browser: 'Microsoft Edge via Playwright', screenshots: '.runtime/screenshots', time: new Date().toISOString() }, null, 2));
    checks.forEach(check => console.log('PASS ' + check));
  } catch (error) {
    await page.screenshot({ path: path.join(output, 'failure.png'), fullPage: true });
    throw error;
  } finally {
    await context.close();
    await browser.close();
  }
})().catch(error => { console.error(error.message); process.exitCode = 1; });
